CONTACT_ROLE_LABELS: dict[str, str] = {
    "recruiter": "рекрутер / HR",
    "hiring_manager": "нанимающий менеджер",
    "team_lead": "руководитель команды",
    "founder": "фаундер / executive",
    "peer": "product / tech peer",
    "general": "контакт в компании",
}

CONTACT_ROLE_UI_LABELS: dict[str, str] = {
    "recruiter": "Рекрутер / HR",
    "hiring_manager": "Нанимающий менеджер",
    "team_lead": "Руководитель команды",
    "founder": "Фаундер / executive",
    "peer": "Product / tech peer",
    "general": "Контакт в компании",
}


def format_linkedin_outreach_prompt(
    *,
    example: str,
    candidate_first_name: str,
    contact_role: str,
    company_name: str,
    vacancy_title: str,
    profile_json: str,
    vacancy_json: str,
    match_context_json: str,
) -> str:
    replacements = {
        "example": example,
        "candidate_first_name": candidate_first_name,
        "contact_role_label": CONTACT_ROLE_LABELS.get(contact_role, CONTACT_ROLE_LABELS["general"]),
        "company_name": company_name or "—",
        "vacancy_title": vacancy_title or "—",
        "profile_json": profile_json,
        "vacancy_json": vacancy_json,
        "match_context_json": match_context_json,
    }
    text = LINKEDIN_OUTREACH_PROMPT
    for key, value in replacements.items():
        text = text.replace("{" + key + "}", value)
    return text
