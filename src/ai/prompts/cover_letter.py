def apply_channel_guidance(
    vacancy_source: str,
    *,
    apply_channel: str = "same",
) -> str:
    """Правило вступления: не дублировать площадку при отклике там же."""
    platform = SOURCE_LABELS.get(vacancy_source, vacancy_source or "площадка")
    if apply_channel == "same":
        return (
            f"Отклик через ту же площадку, где размещена вакансия ({platform}). "
            f"НЕ пиши, что нашёл(ла) вакансию на {platform} — при отклике через неё это избыточно. "
            f"Достаточно: «Откликаюсь на вакансию «…»» и при необходимости название компании."
        )
    other = SOURCE_LABELS.get(apply_channel, apply_channel)
    return (
        f"Отклик НЕ через площадку вакансии (вакансия на {platform}, отклик — через {other}). "
        f"Кратко укажи, где увидел(а) вакансию, и что откликаешься на «…»."
    )


def format_cover_letter_prompt(
    *,
    example: str,
    target_role_label: str,
    role_guidance: str,
    apply_channel_guidance: str,
    candidate_role_title: str,
    profile_json: str,
    vacancy_json: str,
    match_context_json: str,
) -> str:
    """Подстановка без str.format — JSON в профиле не ломает шаблон."""
    replacements = {
        "example": example,
        "target_role_label": target_role_label,
        "role_guidance": role_guidance,
        "apply_channel_guidance": apply_channel_guidance,
        "candidate_role_title": candidate_role_title,
        "profile_json": profile_json,
        "vacancy_json": vacancy_json,
        "match_context_json": match_context_json,
    }
    text = COVER_LETTER_PROMPT
    for key, value in replacements.items():
        text = text.replace("{" + key + "}", value)
    return text
