def format_cover_letter_prompt(
    *,
    example: str,
    target_role_label: str,
    role_guidance: str,
    candidate_first_name: str,
    candidate_role_title: str,
    profile_json: str,
    vacancy_json: str,
    match_context_json: str,
) -> str:
    """Подстановка без str.format — JSON в профиле не ломает шаблон."""
    replacements = {
        "example": example,
        "target_role_label": target_role_label,
        "role_guidance": role_guidance,
        "candidate_first_name": candidate_first_name,
        "candidate_role_title": candidate_role_title,
        "profile_json": profile_json,
        "vacancy_json": vacancy_json,
        "match_context_json": match_context_json,
    }
    text = COVER_LETTER_PROMPT
    for key, value in replacements.items():
        text = text.replace("{" + key + "}", value)
    return text
